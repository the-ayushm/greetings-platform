// Fonts for the "Royal Burgundy" wedding invitation, self-hosted like the other templates'
// (the renderer CSP only allows font-src 'self'). Pinyon Script (names, headings) and
// Cormorant Garamond (invitation text) — both SIL Open Font License 1.1.
// Run: node scripts/fetch-wedding-fonts.mjs   (output is committed; nothing is fetched at runtime)
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const CSS_URL = "https://fonts.googleapis.com/css2?family=Pinyon+Script&family=Cormorant+Garamond:ital,wght@0,400;0,500;0,600;1,400&display=swap";
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36";
const LICENSES = {
  "pinyonscript-OFL.txt": "https://raw.githubusercontent.com/google/fonts/main/ofl/pinyonscript/OFL.txt",
  "cormorantgaramond-OFL.txt": "https://raw.githubusercontent.com/google/fonts/main/ofl/cormorantgaramond/OFL.txt",
};
const CSS_OUT = path.resolve("src/templates/wedding/fonts.css");
const OUT = path.resolve("public/fonts");

fs.mkdirSync(path.join(OUT, "licenses"), { recursive: true });
let css = await (await fetch(CSS_URL, { headers: { "user-agent": UA } })).text();
const urls = [...new Set([...css.matchAll(/url\((https:[^)]+)\)/g)].map((m) => m[1]))];
for (const u of urls) {
  const buf = Buffer.from(await (await fetch(u, { headers: { "user-agent": UA } })).arrayBuffer());
  const name = crypto.createHash("sha256").update(u).digest("hex").slice(0, 16) + ".woff2";
  fs.writeFileSync(path.join(OUT, name), buf);
  css = css.split(u).join(`/fonts/${name}`);
}
for (const [file, url] of Object.entries(LICENSES)) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`licence download failed: ${url}`);
  fs.writeFileSync(path.join(OUT, "licenses", file), await r.text());
}
fs.writeFileSync(CSS_OUT, `/* Generated by scripts/fetch-wedding-fonts.mjs from Google Fonts (SIL OFL 1.1). Do not edit. */\n${css}`);
console.log(`${urls.length} font files written to ${OUT}`);
