/**
 * Writes the SQL data migration that registers a template version with its default content
 * (generated from the template's defaults.ts so the DB and code can never drift), and its
 * first product. Run:
 *   npx tsx scripts/gen-template-migration.ts             # scrapbook (…0004)
 *   npx tsx scripts/gen-template-migration.ts lovestory   # Our Little Universe (…20261013000002)
 *   npx tsx scripts/gen-template-migration.ts wedding     # Royal Burgundy wedding invitation (…20261028000002)
 */
import fs from "node:fs";
import { newSiteContent as newScrapbook } from "../src/templates/scrapbook/defaults";
import { SCHEMA_VERSION as SCRAPBOOK_SCHEMA, draftContentSchema as scrapbookDraft } from "../src/templates/scrapbook/schema";
import { newSiteContent as newLoveStory } from "../src/templates/lovestory/defaults";
import { SCHEMA_VERSION as LOVE_SCHEMA, draftContentSchema as loveDraft } from "../src/templates/lovestory/schema";
import { newSiteContent as newWedding } from "../src/templates/wedding/defaults";
import { SCHEMA_VERSION as WEDDING_SCHEMA, draftContentSchema as weddingDraft } from "../src/templates/wedding/schema";

const q = (s: string) => s.replace(/'/g, "''");

function scrapbook() {
  const json = q(JSON.stringify(scrapbookDraft.parse(newScrapbook())));
  return {
    file: "supabase/migrations/20261005000004_seed_scrapbook_template.sql",
    bytes: json.length,
    sql: `-- Generated by scripts/gen-template-migration.ts — do not edit by hand.
insert into public.templates (key, name, description, sort)
values ('scrapbook', 'Scrapbook Surprise', 'Pink pastel scrapbook: envelope letter, polaroid memories, coupons, our-song player, cupcake wish and a final surprise.', 1)
on conflict (key) do nothing;

insert into public.template_versions (template_key, version, schema_version, default_content, is_current, notes)
values ('scrapbook', 1, ${SCRAPBOOK_SCHEMA}, '${json}'::jsonb, true, 'Initial release (port of the original single-file experience).')
on conflict (template_key, version) do nothing;

-- V1 product. Price is editable from the admin dashboard (₹499.00 = 49900 paise).
insert into public.products (template_key, name, description, price_paise, currency, edit_days, live_days)
select 'scrapbook', 'Scrapbook Surprise — personal website', 'Your own private birthday website: 30 days to edit, live for 1 year.', 49900, 'INR', 30, 365
where not exists (select 1 from public.products where template_key = 'scrapbook');
`,
  };
}

function lovestory() {
  const json = q(JSON.stringify(loveDraft.parse(newLoveStory())));
  return {
    file: "supabase/migrations/20261013000002_seed_love_story_template.sql",
    bytes: json.length,
    sql: `-- Generated by scripts/gen-template-migration.ts lovestory — do not edit by hand.
insert into public.templates (key, name, description, sort)
values ('lovestory', 'Our Little Universe', 'A personalised love story website: welcome under fairy lights, little questions, our timeline, scrapbook, special dates, love letter, coupons, photo wall and a final surprise.', 2)
on conflict (key) do nothing;

insert into public.template_versions (template_key, version, schema_version, default_content, is_current, notes)
values ('lovestory', 1, ${LOVE_SCHEMA}, '${json}'::jsonb, true, 'Initial release: 15-section romantic story experience.')
on conflict (template_key, version) do nothing;

-- Product row. The initial price mirrors the existing product (₹499.00 = 49900 paise); change
-- it in Admin → Templates & pricing — this insert never touches an existing row.
insert into public.products (template_key, name, description, price_paise, currency, edit_days, live_days)
select 'lovestory', 'Our Little Universe — love story website', 'A personalised, interactive love story website: 30 days to edit, live for 1 year.', 49900, 'INR', 30, 365
where not exists (select 1 from public.products where template_key = 'lovestory');
`,
  };
}

function wedding() {
  const json = q(JSON.stringify(weddingDraft.parse(newWedding())));
  return {
    file: "supabase/migrations/20261028000002_seed_wedding_template.sql",
    bytes: json.length,
    sql: `-- Generated by scripts/gen-template-migration.ts wedding — do not edit by hand.
insert into public.templates (key, name, description, sort)
values ('wedding', 'Royal Burgundy', 'An interactive wedding invitation: envelope opening with a wax seal, couple names, live countdown, event schedule, venue map, dress code, RSVP and save-the-date.', 3)
on conflict (key) do nothing;

insert into public.template_versions (template_key, version, schema_version, default_content, is_current, notes)
values ('wedding', 1, ${WEDDING_SCHEMA}, '${json}'::jsonb, true, 'Initial release: Royal Burgundy interactive wedding invitation.')
on conflict (template_key, version) do nothing;

-- Product row, created NOT on sale (is_active = false) at ₹0 for testing: only admins with an
-- MFA session can see its page and get it. Publish it and set the price in Admin → Templates &
-- pricing. This insert never touches an existing row (safe to re-run).
insert into public.products (template_key, name, description, price_paise, currency, edit_days, live_days, is_active)
select 'wedding', 'Royal Burgundy — Interactive Wedding Invitation Website', 'An elegant, interactive wedding invitation featuring a cinematic envelope-opening animation, personalized couple names, live countdown, event schedule, venue map, dress code, and RSVP functionality.', 0, 'INR', 90, 365, false
where not exists (select 1 from public.products where template_key = 'wedding');
`,
  };
}

const which = process.argv[2] ?? "scrapbook";
const out = which === "lovestory" ? lovestory() : which === "scrapbook" ? scrapbook() : which === "wedding" ? wedding() : null;
if (!out) {
  console.error(`unknown template "${which}" (expected scrapbook, lovestory or wedding)`);
  process.exit(1);
}
fs.writeFileSync(out.file, out.sql);
console.log("wrote", out.file, out.bytes, "bytes of content");
