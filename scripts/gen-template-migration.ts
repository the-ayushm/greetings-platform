const which = process.argv[2] ?? "scrapbook";
const out = which === "lovestory" ? lovestory() : which === "scrapbook" ? scrapbook() : which === "wedding" ? wedding() : which === "doyouloveme" ? doyouloveme() : which === "vivah" ? vivah() : null;
if (!out) {
  console.error(`unknown template "${which}" (expected scrapbook, lovestory, wedding, doyouloveme or vivah)`);
  process.exit(1);
}
fs.writeFileSync(out.file, out.sql);
console.log("wrote", out.file, out.bytes, "bytes of content");
